import * as path from 'node:path';
import { ProjectPaths, QuestaConfig } from '../types';

function tclArg(value: string): string {
  // Braces preserve spaces. A brace in a filesystem path is rare but is escaped safely for Tcl.
  return `{${value.replace(/\\/g, '/').replace(/[{}]/g, '\\$&')}}`;
}

function vlogArguments(config: QuestaConfig, workspace: string): string[] {
  const includes = config.includeDirectories.map(dir => tclArg(`+incdir+${path.isAbsolute(dir) ? dir : path.resolve(workspace, dir)}`));
  const macros = config.macroDefinitions.filter(Boolean).map(macro => tclArg(`+define+${macro}`));
  return ['-work', 'work', '-sv', ...includes, ...macros, ...config.additionalVlogArguments.map(tclArg)];
}

export function generateRunDo(paths: ProjectPaths, config: QuestaConfig): string {
  if (!config.topModule) { throw new Error('No top module configured. Use "Questa: Select Top Module".'); }
  if (!/^[A-Za-z_][A-Za-z0-9_$]*$/.test(config.topModule)) { throw new Error('The configured top module is not a valid Verilog identifier.'); }
  const vlog = vlogArguments(config, paths.workspace).join(' ');
  const isGui = config.simulationMode === 'gui';
  // Default optimization strips signal visibility; +acc keeps everything waveform-loggable in GUI mode.
  const vsim = [...(isGui ? ['-voptargs=+acc'] : []), ...config.additionalVsimArguments.map(tclArg), `work.${config.topModule}`].join(' ');
  return [
    '# Generated by QuestaSim for VS Code. Edit your own run.do separately; this file may be regenerated.',
    'onerror {quit -code 1}',
    `set questa_workspace ${tclArg(paths.workspace)}`,
    'set questa_simulation_directory [pwd]',
    'if {![file exists work]} {vlib work}',
    'vmap work work',
    'cd $questa_workspace',
    `vlog ${vlog} -f ${tclArg(paths.sourceList)}`,
    'cd $questa_simulation_directory',
    `vsim ${vsim}`,
    // GUI runs stay open so the waveform is visible; console runs quit once finished.
    ...(isGui ? ['add wave -r /*', 'run -all', 'wave zoom full'] : ['run -all', 'quit -f']),
    ''
  ].join('\n');
}
