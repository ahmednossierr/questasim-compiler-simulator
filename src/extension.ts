import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import * as vscode from 'vscode';
import { getConfig, projectPaths, updateTopModule, workspaceFolder } from './services/projectConfig';
import { discoverSources, sourceListText } from './services/sourceScanner';
import { generateRunDo } from './services/runDoGenerator';
import { QuestaService } from './services/questaService';
import { Transcript } from './ui/output';
import { ProjectPaths, QuestaConfig } from './types';

const GENERATED_MARKER = '# Generated by QuestaSim for VS Code.';

export function activate(context: vscode.ExtensionContext): void {
  const transcript = new Transcript();
  const service = new QuestaService(transcript);
  const status = vscode.window.createStatusBarItem(vscode.StatusBarAlignment.Left, 100);
  status.text = '$(play) Questa';
  status.tooltip = 'QuestaSim commands';
  status.command = 'questa.statusMenu';
  status.show();
  context.subscriptions.push(transcript.channel, status);

  const requireWorkspace = (): { folder: vscode.WorkspaceFolder; paths: ProjectPaths; config: QuestaConfig } | undefined => {
    const folder = workspaceFolder();
    if (!folder) {
      void vscode.window.showErrorMessage('Open a Verilog/SystemVerilog workspace before using QuestaSim.');
      return undefined;
    }
    const config = getConfig();
    return { folder, config, paths: projectPaths(folder.uri.fsPath, config) };
  };

  const generateSources = async (): Promise<ProjectPaths | undefined> => {
    const project = requireWorkspace();
    if (!project) { return undefined; }
    const excluded = [...project.config.excludedDirectories, path.basename(project.paths.simulationDirectory)];
    const sources = await discoverSources(project.paths.workspace, { excludedDirectories: excluded, sourceOrder: project.config.sourceOrder });
    if (!sources.length) { throw new Error('No Verilog/SystemVerilog source files were found in this workspace.'); }
    await fs.mkdir(path.dirname(project.paths.sourceList), { recursive: true });
    await fs.writeFile(project.paths.sourceList, sourceListText(project.paths.workspace, sources), 'utf8');
    transcript.info(`Generated source list with ${sources.length} file(s): ${project.paths.sourceList}`);
    return project.paths;
  };

  const ensureTopModule = async (): Promise<string | undefined> => {
    const top = getConfig().topModule;
    if (top) { return top; }
    await vscode.window.showErrorMessage('No top module configured. Use "Questa: Select Top Module".');
    return undefined;
  };

  const writeGeneratedRunDo = async (forceGui = false): Promise<string | undefined> => {
    const project = requireWorkspace();
    if (!project || !(await ensureTopModule())) { return undefined; }
    await fs.mkdir(project.paths.simulationDirectory, { recursive: true });
    let target = project.paths.runDo;
    try {
      const existing = await fs.readFile(target, 'utf8');
      if (!existing.startsWith(GENERATED_MARKER)) {
        const action = await vscode.window.showWarningMessage(
          `An existing run.do was found at ${target}. It will not be overwritten.`,
          'Create run_generated.do', 'Overwrite Existing run.do'
        );
        if (action === 'Create run_generated.do') {
          target = path.join(project.paths.simulationDirectory, 'run_generated.do');
        } else if (action !== 'Overwrite Existing run.do') {
          return undefined;
        }
      }
    } catch { /* A missing target is expected on first generation. */ }
    const config = { ...project.config, topModule: getConfig().topModule, simulationMode: forceGui ? ('gui' as const) : project.config.simulationMode };
    await fs.writeFile(target, generateRunDo({ ...project.paths, runDo: target }, config), 'utf8');
    transcript.info(`Generated run script: ${target}`);
    return target;
  };

  async function withProgress<T>(title: string, work: () => Promise<T>): Promise<T | undefined> {
    try {
      return await vscode.window.withProgress({ location: vscode.ProgressLocation.Notification, title }, work);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      transcript.info(`ERROR: ${message}`);
      transcript.show();
      await vscode.window.showErrorMessage(message);
      return undefined;
    }
  }

  const command = (id: string, callback: (...args: never[]) => unknown) => context.subscriptions.push(vscode.commands.registerCommand(id, callback));
  command('questa.generateSourceList', async () => { await withProgress('Questa: Generating source list', generateSources); });
  command('questa.refreshSources', async () => { await withProgress('Questa: Refreshing sources', generateSources); });
  command('questa.generateRunDo', async () => { await withProgress('Questa: Generating run.do', writeGeneratedRunDo); });
  command('questa.showTranscript', () => transcript.show());
  command('questa.clearTranscript', () => transcript.clear());

  command('questa.selectTopModule', async () => {
    const project = requireWorkspace();
    if (!project) { return; }
    const sources = await discoverSources(project.paths.workspace, { excludedDirectories: project.config.excludedDirectories });
    const choices: vscode.QuickPickItem[] = [
      { label: '$(edit) Enter top-module name manually', description: 'Type a module name such as alu_tb' },
      ...sources.filter(file => ['.v', '.sv'].includes(path.extname(file).toLowerCase())).map(file => ({ label: path.relative(project.paths.workspace, file), description: 'Use a module declared in this file' }))
    ];
    const choice = await vscode.window.showQuickPick(choices, { placeHolder: 'Select a source file or enter the top module name' });
    if (!choice) { return; }
    let suggested = '';
    if (choice.label.startsWith('$(edit)')) {
      suggested = getConfig().topModule;
    } else {
      try {
        const text = await fs.readFile(path.resolve(project.paths.workspace, choice.label), 'utf8');
        suggested = /\bmodule\s+([A-Za-z_][A-Za-z0-9_$]*)/.exec(text)?.[1] ?? path.basename(choice.label, path.extname(choice.label));
      } catch { suggested = path.basename(choice.label, path.extname(choice.label)); }
    }
    const topModule = await vscode.window.showInputBox({ prompt: 'Top-level module', value: suggested, validateInput: value => /^[A-Za-z_][A-Za-z0-9_$]*$/.test(value.trim()) ? undefined : 'Enter a valid Verilog module identifier.' });
    if (!topModule) { return; }
    await updateTopModule(topModule.trim());
    transcript.info(`Top module set to ${topModule.trim()}.`);
    void vscode.window.showInformationMessage(`Questa top module: ${topModule.trim()}`);
  });

  command('questa.compile', async () => {
    await withProgress('Questa: Compiling', async () => {
      const paths = await generateSources(); if (!paths) { return; }
      // Generate or refresh a managed run script when a top module is configured; compilation itself does not need one.
      if (getConfig().topModule) { await writeGeneratedRunDo(); }
      const project = requireWorkspace(); if (!project) { return; }
      await service.compile(project.paths, project.config);
      transcript.show();
    });
  });

  const run = async (runDo?: string, forceGui = false): Promise<void> => {
    const project = requireWorkspace(); if (!project) { return; }
    const managedScript = runDo === undefined;
    const script = runDo ?? await writeGeneratedRunDo(forceGui); if (!script) { return; }
    const config = forceGui ? { ...project.config, simulationMode: 'gui' as const } : project.config;
    if (config.useIntegratedTerminal) {
      const { vsim } = await service.resolveExecutables(config);
      const args = [
        ...(managedScript ? [] : config.additionalVsimArguments),
        ...(config.simulationMode === 'console' ? ['-c'] : []),
        '-do', `do {${script.replace(/\\/g, '/').replace(/[{}]/g, '\\$&')}}`
      ];
      launchSimulationTerminal(vsim, args, managedScript ? project.paths.simulationDirectory : path.dirname(script));
      transcript.info('Simulation launched in the integrated terminal (questa.useIntegratedTerminal).');
    } else {
      await service.run(project.paths, config, script, !managedScript, managedScript ? project.paths.simulationDirectory : path.dirname(script));
    }
    transcript.show();
  };
  command('questa.runSimulation', async () => { await withProgress('Questa: Running simulation', () => run()); });
  command('questa.openWaveform', async () => { await withProgress('Questa: Opening GUI simulation', () => run(undefined, true)); });

  command('questa.runExistingRunDo', async () => {
    const project = requireWorkspace(); if (!project) { return; }
    const found = await vscode.workspace.findFiles('**/run.do', '{**/.git/**,**/node_modules/**,**/.vscode/**,**/work/**,**/build/**}', 100);
    const selected = found.length === 1 ? found[0] : await vscode.window.showQuickPick(found.map(uri => ({ label: vscode.workspace.asRelativePath(uri), uri })), { placeHolder: 'Select an existing run.do to execute' });
    if (!selected) { if (!found.length) { void vscode.window.showInformationMessage('No run.do found. Select or generate one first.'); } return; }
    const uri = 'uri' in selected ? selected.uri : selected;
    await withProgress('Questa: Running existing run.do', () => run(uri.fsPath));
  });

  command('questa.statusMenu', async () => {
    const action = await vscode.window.showQuickPick([
      'Compile', 'Run Simulation', 'Generate Source List', 'Generate run.do', 'Select Top Module', 'Run Existing run.do', 'Open Transcript', 'Settings'
    ], { placeHolder: 'QuestaSim' });
    const commands: Record<string, string> = {
      'Compile': 'questa.compile', 'Run Simulation': 'questa.runSimulation', 'Generate Source List': 'questa.generateSourceList', 'Generate run.do': 'questa.generateRunDo', 'Select Top Module': 'questa.selectTopModule', 'Run Existing run.do': 'questa.runExistingRunDo', 'Open Transcript': 'questa.showTranscript', 'Settings': 'workbench.action.openSettings'
    };
    if (action) { await vscode.commands.executeCommand(commands[action], action === 'Settings' ? 'questa' : undefined); }
  });

  let refreshTimer: NodeJS.Timeout | undefined;
  const watcher = vscode.workspace.createFileSystemWatcher('**/*.{v,sv,vh,svh}');
  const scheduleRefresh = (): void => {
    if (!getConfig().autoGenerateSourceList) { return; }
    if (refreshTimer) { clearTimeout(refreshTimer); }
    refreshTimer = setTimeout(() => { void generateSources().catch(error => transcript.info(`Source refresh failed: ${String(error)}`)); }, 400);
  };
  watcher.onDidCreate(scheduleRefresh); watcher.onDidChange(scheduleRefresh); watcher.onDidDelete(scheduleRefresh);
  context.subscriptions.push(watcher, { dispose: () => refreshTimer && clearTimeout(refreshTimer) });
}

export function deactivate(): void { /* subscriptions release processes and UI resources */ }

function launchSimulationTerminal(executable: string, args: string[], cwd: string): void {
  if (args.some(argument => argument.includes('\u0000') || argument.includes('"'))) {
    throw new Error('Cannot launch an integrated terminal command containing a quote or NUL character. Use the Output channel mode instead.');
  }
  const windows = process.platform === 'win32';
  const quote = (value: string): string => windows
    ? `"${value.replace(/%/g, '%%').replace(/\^/g, '^^')}"`
    : `'${value.replace(/'/g, `'"'"'`)}'`;
  const terminal = vscode.window.createTerminal({
    name: 'QuestaSim',
    cwd,
    shellPath: windows ? (process.env.ComSpec ?? 'cmd.exe') : '/bin/sh',
    shellArgs: windows ? ['/d', '/q', '/v:off'] : []
  });
  terminal.show(true);
  terminal.sendText([executable, ...args].map(quote).join(' '), true);
}
